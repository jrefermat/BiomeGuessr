function shuffleInPlace<T>(arr: T[]): T[] {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

let remainingQueue: GeoLocation[] = [];

function refillQueue() {
  remainingQueue = shuffleInPlace([...locations]);
}

export function pickRandomLocations(count: number): GeoLocation[] {
  if (remainingQueue.length < count) {
    refillQueue();
  }
  const picked = remainingQueue.slice(0, count);
  remainingQueue = remainingQueue.slice(count);
  return picked;
}
